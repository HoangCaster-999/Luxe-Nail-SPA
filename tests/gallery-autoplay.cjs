// Run a local server on port 8765, then: node tests/gallery-autoplay.cjs (requires Playwright).
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const out = path.join(process.env.TEMP || '/tmp', 'luxe-gallery-qa');
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install();
    await page.goto(process.env.SITE_URL || 'http://127.0.0.1:8765', { waitUntil: 'domcontentloaded' });
    const schema = await page.locator('script[type="application/ld+json"]').textContent();
    assert.equal(JSON.parse(schema).email, 'Luxenailandspa27@gmail.com');
    assert.equal(JSON.parse(schema).paymentAccepted, 'Cash');
    assert.equal(await page.locator('a[href="mailto:Luxenailandspa27@gmail.com"]').count(), 2);
    const bookingLinks = page.locator('a').filter({ hasText: /Book Now|Book by email/ });
    assert.ok(await bookingLinks.count() > 9);
    for (const href of await bookingLinks.evaluateAll(links => links.map(link => link.getAttribute('href')))) {
      const url = new URL(href);
      assert.equal(url.protocol, 'mailto:');
      assert.equal(url.pathname, 'Luxenailandspa27@gmail.com');
      assert.match(url.searchParams.get('subject'), /Appointment request/);
      assert.match(url.searchParams.get('body'), /Preferred date:.*\r\nPreferred time:/);
    }
    const treatmentBooking = new URL(await page.locator('.menu-card .svc__book').first().getAttribute('href'));
    const treatmentName = await page.locator('.menu-card h3').first().innerText();
    assert.equal(treatmentBooking.searchParams.get('subject'), `Appointment request - ${treatmentName}`);
    assert.ok(treatmentBooking.searchParams.get('body').includes(`Service: ${treatmentName}`));
    assert.match(await page.locator('.hero__payment').innerText(), /Cash only/);
    assert.match(await page.locator('#contact .payment-note').innerText(), /Cash only/);
    assert.equal(await page.locator('.about__media img[src*="retouched/"]').count(), 3);
    assert.deepEqual(await page.locator('.about__details img').evaluateAll(images => images.map(img => getComputedStyle(img).objectFit)), ['cover', 'cover']);
    assert.deepEqual(await page.locator('.nav a').evaluateAll(links => links.map(link => link.getAttribute('href'))), ['#top', '#gallery', '#services', '#prices', '#contact']);
    assert.equal(await page.evaluate(() => !!(document.querySelector('#gallery').compareDocumentPosition(document.querySelector('#services')) & Node.DOCUMENT_POSITION_FOLLOWING)), true);
    await page.locator('.hero__art img').evaluate(img => img.decode());
    await page.screenshot({ path: path.join(out, 'desktop-hero.png'), style: '.reveal{opacity:1;transform:none;transition:none}' });
    for (const img of await page.locator('.about__media img').all()) await img.evaluate(img => img.decode());
    await page.locator('#about').screenshot({ path: path.join(out, 'about.png'), style: '.header,.quickbar{visibility:hidden}.reveal{opacity:1;transform:none;transition:none}' });
    await page.locator('.gallery__featured').scrollIntoViewIfNeeded();
    await page.waitForTimeout(150);
    await page.clock.runFor(300);
    const counter = page.locator('.gallery__counter');
    const playback = page.locator('[data-gallery-playback]');
    assert.equal(await counter.innerText(), '1 / 14');
    await page.clock.runFor(4700);
    assert.equal(await counter.innerText(), '2 / 14', 'Autoplay should advance without a click');
    await playback.click();
    const paused = await counter.innerText();
    await page.clock.runFor(10000);
    assert.equal(await counter.innerText(), paused, 'Pause should hold the current slide');
    await playback.click();
    await page.clock.runFor(4700);
    assert.notEqual(await counter.innerText(), paused, 'Play should resume');
    await page.locator('.gallery__featured').click();
    const enlarged = await counter.innerText();
    await page.clock.runFor(10000);
    assert.equal(await counter.innerText(), enlarged, 'Autoplay should pause while the lightbox is open');
    await page.locator('.lightbox__close').click();
    await page.locator('.masonry__item').last().click();
    assert.equal(await counter.innerText(), '14 / 14');
    assert.equal(await playback.innerText(), 'Play slideshow');
    await playback.click();
    await page.clock.runFor(4700);
    assert.equal(await counter.innerText(), '1 / 14', 'The slideshow should wrap to the first photograph');
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.waitForTimeout(150);
    await page.clock.runFor(300);
    const offscreen = await counter.innerText();
    await page.clock.runFor(10000);
    assert.equal(await counter.innerText(), offscreen, 'Offscreen slideshow should pause');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('.gallery__featured').scrollIntoViewIfNeeded();
    await page.waitForTimeout(150);
    await page.clock.runFor(10000);
    assert.equal(await counter.innerText(), offscreen, 'Reduced motion should disable automatic playback');
    for (const width of [390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}`);
    }
    await page.locator('#contact').screenshot({ path: path.join(out, 'contact.png'), style: '.header,.quickbar{visibility:hidden}' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await page.screenshot({ path: path.join(out, 'mobile-hero.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.locator('.masonry__item').first().click();
    await page.locator('.gallery__controls [data-gallery-dir="1"]').click();
    assert.equal(await page.locator('.gallery__track').evaluate(track => track.getAnimations().length), 1, 'Slide changes should animate the horizontal track');
    await page.waitForTimeout(750);
    assert.match(await page.locator('#gallery-image').getAttribute('src'), /magenta-gold-florals/);
    assert.equal(await page.locator('.gallery__featured').evaluate(element => Math.abs(element.getBoundingClientRect().left + element.getBoundingClientRect().width / 2 - innerWidth / 2) < 1), true, 'The new photograph should finish in the centre');
    await page.locator('.gallery__controls [data-gallery-dir="1"]').click();
    await page.locator('.gallery__controls [data-gallery-dir="1"]').click();
    await page.locator('.gallery__controls [data-gallery-dir="-1"]').click();
    await page.waitForTimeout(750);
    assert.match(await page.locator('#gallery-image').getAttribute('src'), /floral-dot-french/);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: 'PASS', checks: ['autoplay', 'pause/resume', 'lightbox pause', 'wraparound', 'offscreen pause', 'reduced motion', 'cash and email', 'four viewport widths'], screenshots: out }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
